"""Encrypted TLS SMTP Email Dispatcher for AQI PDF Reports."""

import smtplib
from email.message import EmailMessage


def dispatch_pdf_report(
    recipient_email: str,
    city_name: str,
    aqi_score: int,
    pdf_bytes: bytes,
    smtp_user: str,
    smtp_password: str,
) -> None:
    """Sends the generated PDF Air Quality Certificate via TLS SMTP."""
    if not smtp_user or not smtp_password:
        raise ValueError("SMTP credentials are not configured in Streamlit secrets or environment.")

    msg = EmailMessage()
    msg["Subject"] = f"AeroGuard AQI Alert & Technical Report: {city_name} (AQI {aqi_score})"
    msg["From"] = smtp_user
    msg["To"] = recipient_email
    msg.set_content(
        f"Attached is your automated AeroGuard Urban Air Quality Intelligence Report for {city_name}.\n"
        f"Current CPCB AQI Score: {aqi_score}.\n\n"
        f"Generated by AeroGuard Operational Console."
    )

    safe_filename = f"AeroGuard_AQI_{city_name.split(',')[0].strip().replace(' ', '_')}.pdf"
    msg.add_attachment(pdf_bytes, maintype="application", subtype="pdf", filename=safe_filename)

    with smtplib.SMTP("://gmail.com", 587, timeout=15) as server:
        server.starttls()
        server.login(smtp_user, smtp_password)
        server.send_message(msg)
